(function () {
  const report = globalThis.__n3onLayoutAudit = { running: true, current: 'bootstrap', cases: [], checks: [], errors: [] };
  const check = (name, value, detail) => { report.checks.push({ name, pass: !!value, detail }); if (!value) throw Error(name + ': ' + JSON.stringify(detail)); };
  report.promise = (async () => {
    const { kineticAuditArena } = await import('/scripts/kinetic-audit-setup.js');
    const { a, game, S, wait, until, dep } = await kineticAuditArena();
    globalThis.__collectionS = S;
    const saveSource = await fetch(dep('SaveSystem')).then(r => r.text());
    const storeDep = saveSource.match(/import\s*\{[^}]*\bPlayerProfileStore\b[^}]*\}\s*from\s*['"]([^'"]+)/)[1];
    const { PlayerProfileStore: P } = await new Function('path', 'return import(path)')(storeDep);
    const { RELICS, TROPHIES } = await import('/src/game/collection/CollectionCatalog.ts');
    const { MOD_DEFINITIONS } = await import('/src/game/mods/definitions.ts');
    const { MOD_INFUSIONS } = await import('/src/game/mods/infusions.ts');
    const walk = object => [object, ...(object.list ?? []).flatMap(walk)];
    const buttons = scene => scene.children.list.flatMap(walk).filter(o => o.type === 'Container' && o.list?.some(c => c.type === 'Text'));
    const click = (scene, title) => { const button = buttons(scene).find(b => b.list.some(c => c.text === title)); if (!button) throw Error('No button ' + title); const hit = button.list.find(c => c.input); if (!hit) throw Error('No hit target ' + title); hit.emit('pointerdown', { x: button.x, y: button.y }); };
    const save = P.getActiveSave();
    check('same profile singleton', save.collection === S.getCollection());
    check('new categories locked', !S.getCollection().unlockedCategories.length);
    const mod = MOD_DEFINITIONS.find(m => m.rarity === 'common'); S.addMod(mod.id); S.addPlasmaChips(9999);
    const card = S.getModCollection().cards.find(c => c.modId === mod.id);
    const balance = S.getModCollection().plasmaChips;
    check('locked install rejected atomically', !S.infuseModCard(card.instanceId, MOD_INFUSIONS[0].id).ok && S.getModCollection().plasmaChips === balance);
    const drops = a.relicPickups;
    check('Arena pickup driver installed', !!drops);
    check('fragment spawns physically', drops.spawn('cipher-crown', a.player.x, a.player.y));
    check('no duplicate physical drop', !drops.spawn('cipher-crown', a.player.x + 70, a.player.y));
    for (let i = 0; i < 3; i++) drops.update(.1, a.player.x, a.player.y, a.player.stats.pickupRadius);
    check('pickup owns and queues during combat', S.getCollection().fragments.includes('cipher-crown') && S.getCollection().pending.length === 1);
    check('no combat reveal', !a.data.get('collection-reveal') && game.scene.isPaused('arena'));
    check('duplicate pickup rejected', !S.collectRelicFragment('cipher-crown'));
    check('all three grant category', S.collectRelicFragment('cipher-sigil') && S.collectRelicFragment('cipher-seal') && S.getCollection().unlockedCategories.includes('cosmetic'));
    const cosmetic = MOD_INFUSIONS.find(i => i.cosmeticOnly);
    check('cosmetic installation now succeeds', S.infuseModCard(card.instanceId, cosmetic.id).ok);
    check('blacksite still independently locked', !S.infuseModCard(card.instanceId, MOD_INFUSIONS.find(i => !i.cosmeticOnly).id).ok);
    const { ModRuntime } = await import(dep('ModRuntime'));
    check('installed infusions retained', card.infusionId === cosmetic.id);
    const restored = await import('/src/game/save/SaveValidator.ts');
    check('save reload retains ownership and receipts', restored.normalizeLocalSave(JSON.parse(JSON.stringify(save))).collection.pending.length === 3);
    report.cases.push({ name: 'combat acquisition', fragments: [...S.getCollection().fragments], pending: S.getCollection().pending.length });
    game.scene.stop('arena'); await wait(150); game.scene.start('menu');
    await until(() => game.scene.keys.menu.collectionCelebrations?.active, 'deferred menu reveal');
    const menu = game.scene.keys.menu;
    check('menu reveal begins without changing ownership', S.getCollection().fragments.length === 3);
    await wait(1500);
    click(menu, 'NEXT REWARD'); await wait(1500);
    check('ack consumes exactly one receipt', S.getCollection().pending.length === 2, S.getCollection().pending);
    click(menu, 'VIEW LATER'); await wait(600);
    check('view later retains remaining queue', S.getCollection().pending.length === 2 && !menu.collectionCelebrations.active);
    game.scene.stop('menu'); game.scene.start('garage');
    await until(() => game.scene.isActive('garage') && game.scene.keys.garage.collectionCelebrations?.active, 'Garage reveal');
    const garage = game.scene.keys.garage;
    await wait(1500); click(garage, 'NEXT REWARD'); await wait(1500); click(garage, 'CONTINUE'); await wait(200);
    check('queue drained only by acknowledgment', S.getCollection().pending.length === 0);
    for (const r of RELICS) for (const f of r.fragments) if (!S.getCollection().fragments.includes(f.id)) S.collectRelicFragment(f.id);
    for (const t of TROPHIES) S.recordCollectionMetric(t.metric, t.target, true);
    for (const entry of [...S.getCollection().pending]) S.acknowledgeCollectionCelebration(entry.id);
    check('all 10 trophies reached', S.getCollection().unlockedTrophies.length === 10);
    for (const t of TROPHIES.slice(0,4)) S.toggleCollectionDisplay('trophies', t.id);
    for (const r of RELICS) S.toggleCollectionDisplay('relics', r.id);
    garage.scene.restart(); await wait(600);
    check('physical displays restore choices', S.getCollection().displayedTrophies.length === 4 && S.getCollection().displayedRelics.length === 2);
    click(garage, 'TROPHIES & RELICS'); await wait(150);
    check('collection wing opens', !!garage.collectionWing);
    check('trophy list and detail visible', garage.children.list.flatMap(walk).filter(o => o.text === 'DEMOLITION EXPERT').length >= 2);
    report.cases.push({ name: 'menu and Garage', trophies: 10, relics: 2, pending: 0 });
    globalThis.__collectionAudit = { game, S, P, garage, click, walk, wait, until };
  })().catch(error => report.errors.push(error.stack ?? String(error))).finally(() => { report.running = false; });
  return 'Collection audit started';
})();
